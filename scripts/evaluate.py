"""Evaluate the pipeline on the sample CV/job pairs and write docs/EVALUATION.md.

For each sample pair it runs the full pipeline N times (default 2) and reports:
- score per reviewer agent and the deterministic overall score
- consistency: overall-score spread / variance between runs
- grounding: verification rate of quoted evidence
- fabrication check on rewrites: [placeholders] vs concrete numbers, and numbers
  that do not appear anywhere in the CV ("new numbers")

Usage (from the repo root):
    python scripts/evaluate.py            # uses DEEPSEEK_API_KEY from .env, else mock mode
    python scripts/evaluate.py --runs 3
"""

from __future__ import annotations

import argparse
import asyncio
import re
import statistics
import sys
import time
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app import llm  # noqa: E402
from app.pipeline import AGENTS, run_review  # noqa: E402

SAMPLES = [("en", "EN · Junior Data Analyst"), ("tr", "TR · Dijital Pazarlama Uzman Yardımcısı")]
PLACEHOLDER_RE = re.compile(r"\[[^\]]+\]")
NUMBER_RE = re.compile(r"\d+(?:[.,]\d+)?")


async def run_once(sample: str) -> dict:
    cv = (ROOT / "samples" / f"cv_{sample}.txt").read_text(encoding="utf-8")
    job = (ROOT / "samples" / f"job_{sample}.txt").read_text(encoding="utf-8")
    started = time.perf_counter()
    final, error = None, None
    async for event in run_review(cv_text=cv, job_text=job, output_language=sample):
        if event["type"] == "final":
            final = event["result"]
        elif event["type"] == "error":
            error = event["message"]
    if final is None:
        return {"error": error or "no result", "elapsed": time.perf_counter() - started}

    rewrites = (final["agents"].get("coach") or {}).get("rewrites", [])
    placeholders = sum(len(PLACEHOLDER_RE.findall(r["improved"])) for r in rewrites)
    concrete_numbers = sum(len(NUMBER_RE.findall(PLACEHOLDER_RE.sub(" ", r["improved"]))) for r in rewrites)
    new_numbers = sorted({n for r in rewrites for n in r.get("new_numbers", [])})
    return {
        "elapsed": time.perf_counter() - started,
        "agent_scores": final["scores"]["agent_scores"],
        "overall": final["scores"]["overall"],
        "must_have": final["scores"]["must_have"]["coverage"],
        "verification": final["verification"],
        "agent_errors": final["agent_errors"],
        "aggregate_ok": final["aggregate"] is not None,
        "rewrites": len(rewrites),
        "placeholders": placeholders,
        "concrete_numbers": concrete_numbers,
        "new_numbers": new_numbers,
        "top_actions": len((final["aggregate"] or {}).get("top_actions", [])),
    }


def fmt_pct(x) -> str:
    return "—" if x is None else f"{x * 100:.0f}%"


async def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--runs", type=int, default=2)
    parser.add_argument("--out", default=str(ROOT / "docs" / "EVALUATION.md"))
    args = parser.parse_args()

    cfg = llm.settings()
    if cfg["mock"]:
        llm.MOCK_DELAYS = {k: 0.0 for k in llm.MOCK_DELAYS}
    mode = "MOCK fixtures (no API key) — numbers below only validate the code path" if cfg["mock"] \
        else f"DeepSeek API, model `{cfg['model']}`"
    print(f"Mode: {mode}")

    lines = [
        "# Evaluation",
        "",
        f"_Generated by `scripts/evaluate.py` on {datetime.now():%Y-%m-%d %H:%M}._  ",
        f"**Mode:** {mode}  ",
        f"**Runs per sample:** {args.runs}",
        "",
    ]
    if cfg["mock"]:
        lines += ["> ⚠️ This report was produced in mock mode, so every run returns the same fixtures (variance 0).",
                  "> Re-run `python scripts/evaluate.py` with `DEEPSEEK_API_KEY` set to get real model metrics.", ""]

    summary_rows = []
    for sample, label in SAMPLES:
        runs = []
        for i in range(args.runs):
            print(f"  {label}: run {i + 1}/{args.runs} …", flush=True)
            runs.append(await run_once(sample))
        ok = [r for r in runs if "error" not in r]

        lines += [f"## {label}", ""]
        header = "| Run | " + " | ".join(a.name for a in AGENTS) + " | Overall | Must-have | Verified quotes | Rewrites | [placeholders] | Concrete numbers | Numbers not in CV | Time |"
        lines += [header, "|" + "---|" * (header.count("|") - 1)]
        for i, r in enumerate(runs, start=1):
            if "error" in r:
                lines.append(f"| {i} | error: {r['error']} |")
                continue
            scores = " | ".join(str(r["agent_scores"].get(a.key, "✖")) for a in AGENTS)
            v = r["verification"]
            lines.append(
                f"| {i} | {scores} | **{r['overall']}** | {fmt_pct(r['must_have'])} | "
                f"{fmt_pct(v['rate'])} ({v['verified']}/{v['checked']}) | {r['rewrites']} | {r['placeholders']} | "
                f"{r['concrete_numbers']} | {', '.join(r['new_numbers']) or '0'} | {r['elapsed']:.1f}s |"
            )
        if ok:
            overalls = [r["overall"] for r in ok]
            spread = max(overalls) - min(overalls)
            variance = statistics.pvariance(overalls) if len(overalls) > 1 else 0.0
            rates = [r["verification"]["rate"] for r in ok if r["verification"]["rate"] is not None]
            mean_rate = sum(rates) / len(rates) if rates else None
            per_agent_spread = {
                a.name: max(s) - min(s)
                for a in AGENTS
                if len(s := [r["agent_scores"][a.key] for r in ok if a.key in r["agent_scores"]]) > 1
            }
            failures = sum(len(r["agent_errors"]) for r in ok)
            lines += [
                "",
                f"- **Consistency:** overall score spread = {spread} points, variance = {variance:.1f}"
                + (f"; per-agent spread: {', '.join(f'{k} {v}' for k, v in per_agent_spread.items())}" if per_agent_spread else ""),
                f"- **Grounding:** mean verification rate = {fmt_pct(mean_rate)}",
                f"- **Fabrication check:** {sum(r['placeholders'] for r in ok)} placeholders vs "
                f"{sum(r['concrete_numbers'] for r in ok)} concrete numbers in rewrites; "
                f"numbers not found in the CV: {sorted({n for r in ok for n in r['new_numbers']}) or 'none'}",
                f"- **Reliability:** {failures} failed agent call(s), aggregator ok in "
                f"{sum(r['aggregate_ok'] for r in ok)}/{len(ok)} runs",
                "",
            ]
            summary_rows.append((label, spread, mean_rate))

    lines += [
        "## How to read this",
        "",
        "- **Spread / variance** of the overall score between identical runs measures consistency. "
        "Reviewer temperature is 0.4, so a few points of spread is expected; >10 points would mean the rubric anchors need tightening.",
        "- **Verification rate** is the share of quoted evidence our code found word-for-word (or ≥90% fuzzy) in the redacted CV. "
        "Unverified quotes are shown to the user with a ⚠ badge, never silently dropped.",
        "- **Placeholders vs concrete numbers:** the Coach must use `[X%]`-style placeholders for unknown metrics. "
        "Concrete numbers are fine only if they already appear in the CV — anything listed under *numbers not in CV* is a potential fabrication and is flagged in the UI.",
        "",
    ]
    Path(args.out).write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {args.out}")
    for label, spread, rate in summary_rows:
        print(f"  {label}: spread={spread}, verification={fmt_pct(rate)}")


if __name__ == "__main__":
    asyncio.run(main())
